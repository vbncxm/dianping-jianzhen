def get_sentiment(text: str):
    """返回 (正词命中数, 负词命中数)"""
    if not text:
        return 0, 0
    p = sum(1 for w in POS_WORDS if w in text)
    n = sum(1 for w in NEG_WORDS if w in text)
    return p, n


def hit_hype(text: str) -> list:
    if not text:
        return []
    low = text.lower()
    out = []
    for w in HYPE_WORDS:
        if w.lower() in low:
            out.append(w)
    return out


def hit_concrete(text: str) -> int:
    if not text:
        return 0
    return sum(1 for w in CONCRETE_WORDS if w in text)


def cliche_hits(text: str) -> int:
    if not text:
        return 0
    return sum(1 for p in CLICHE_PATTERNS if p.search(text))
